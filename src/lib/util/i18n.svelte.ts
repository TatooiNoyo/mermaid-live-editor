const messages: Record<Locale, Record<TranslationKey, string>> = { en, 'zh-CN': zhCN };
const STORAGE_KEY = 'mermaid-live-editor-locale';

export const i18n = $state<{ current: Locale }>({ current: 'en' });

const normalizeLocale = (value: string | null | undefined): Locale =>
  value?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';

const applyLocale = (locale: Locale) => {
  i18n.current = locale;
  if (browser) document.documentElement.lang = locale;
};

export const initLocale = () => {
  if (!browser) return;
  let storedLocale: string | null = null;
  try {
    storedLocale = globalThis.localStorage?.getItem(STORAGE_KEY) ?? null;
  } catch {
    // Storage can be disabled by browser privacy settings.
  }
  applyLocale(normalizeLocale(storedLocale ?? navigator.language));
};

export const setLocale = (locale: Locale) => {
  applyLocale(locale);
  if (!browser) return;
  try {
    globalThis.localStorage?.setItem(STORAGE_KEY, locale);
  } catch {
    // The in-memory selection still works when storage is unavailable.
  }
};

export const t = (key: TranslationKey, values: Record<string, string | number> = {}) =>
  Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    messages[i18n.current][key]
  );
